#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {assertCatalogue,assertCaptureRecord}=require('./catalogue-policy.cjs');
const root=path.resolve(__dirname,'..');
const c=JSON.parse(fs.readFileSync(path.join(root,'catalogue.json'),'utf8'));
const b=JSON.parse(fs.readFileSync(path.join(__dirname,'initial-pins.json'),'utf8'));
const clone=()=>JSON.parse(JSON.stringify(c));
assertCatalogue(c,b);
function reject(f,label){const d=clone();f(d);assert.throws(()=>assertCatalogue(d,b),undefined,label);}
reject(x=>x.references[5].ref=x.references.at(-1).ref,'historic pin changed');
reject(x=>x.references[5].blob_sha=x.references.at(-1).blob_sha,'historic blob changed');
reject(x=>x.references[0].image.url='https://example.com/new.png','primary benchmark replaced');
reject(x=>x.references.at(-1).source_url='https://github.com/techrote/tokensplurge/blob/main/environments/001-the-aeolian-palimpsest.html','moving URL');
reject(x=>x.references.at(-1).capture.detail='captures/rivers-detail.png','collision with old image');
reject(x=>x.references.splice(7,1),'historic card removed');
reject(x=>x.references.find(e=>e.id==='aeolian-palimpsest').ref=x.references.at(-1).ref,'curation-01 revision shifted');
reject(x=>x.references.find(e=>e.id==='aeolian-palimpsest').capture.desktop='captures/lantern-ossuary-desktop.png','curation-01 capture overwritten');
reject(x=>x.references.splice(x.references.findIndex(e=>e.id==='aeolian-palimpsest'),1),'prior-curation entry removed');
reject(x=>x.references.find(e=>e.id==='lantern-ossuary').ref=x.references.at(-1).ref,'curation-02 revision shifted');
reject(x=>x.references.find(e=>e.id==='lantern-ossuary').blob_sha=x.references.at(-1).blob_sha,'curation-02 blob shifted');
reject(x=>x.references.find(e=>e.id==='lantern-ossuary').capture.detail='captures/thirst-of-the-sky-detail.png','curation-02 image overwritten');
reject(x=>x.references.splice(x.references.findIndex(e=>e.id==='lantern-ossuary'),1),'curation-02 card removed');
reject(x=>x.references.find(e=>e.id==='thirst-of-the-sky').ref=x.references.at(-1).ref,'curation-03 revision shifted');
reject(x=>x.references.find(e=>e.id==='thirst-of-the-sky').blob_sha=x.references.at(-1).blob_sha,'curation-03 blob shifted');
reject(x=>x.references.find(e=>e.id==='thirst-of-the-sky').capture.desktop='captures/breathing-citadel-desktop.png','curation-03 PNG path reused');
reject(x=>x.references.splice(x.references.findIndex(e=>e.id==='thirst-of-the-sky'),1),'curation-03 card removed');
const x=c.references.at(-1),e={id:x.id,ref:x.ref,path:x.path,blob_sha:x.blob_sha,status:'captured',files:[{path:x.capture.desktop},{path:x.capture.detail}]};
assertCaptureRecord(x,e);
assert.throws(()=>assertCaptureRecord(x,{...e,ref:c.references[5].ref}),undefined,'mixed commit');
assert.throws(()=>assertCaptureRecord(x,{...e,blob_sha:c.references[5].blob_sha}),undefined,'mixed source blob');
console.log('PASS: historical pin lock, mixed revisions, benchmark custody, capture identity and collisions');
